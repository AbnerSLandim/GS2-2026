CREATE TABLE REGIOES (
    ID_REGIAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME_REGIAO VARCHAR2(100) NOT NULL,
    CIDADE VARCHAR2(100) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    CONSTRAINT PK_REGIOES PRIMARY KEY (ID_REGIAO)
);

CREATE TABLE DADOS_CLIMATICOS (
    ID_CLIMA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_REGIAO NUMBER NOT NULL,
    DATA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRECIPITACAO_MM NUMBER(10,2),
    VELOCIDADE_VENTO NUMBER(10,2),
    TEMPERATURA NUMBER(5,2),
    UMIDADE NUMBER(5,2),
    TIPO_DADO VARCHAR2(20),
    CONSTRAINT PK_DADOS_CLIMATICOS PRIMARY KEY (ID_CLIMA),
    CONSTRAINT FK_CLIMA_REGIAO FOREIGN KEY (ID_REGIAO)
        REFERENCES REGIOES(ID_REGIAO),
    CONSTRAINT CK_TIPO_DADO CHECK (
        TIPO_DADO IN ('PREVISAO', 'OBSERVACAO', 'SENSOR')
    )
);

CREATE TABLE OCORRENCIAS (
    ID_OCORRENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_REGIAO NUMBER NOT NULL,
    DATA_OCORRENCIA DATE NOT NULL,
    TIPO_OCORRENCIA VARCHAR2(50) NOT NULL,
    GRAVIDADE VARCHAR2(20),
    DESCRICAO VARCHAR2(500),
    CONSTRAINT PK_OCORRENCIAS PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT FK_OCORRENCIA_REGIAO FOREIGN KEY (ID_REGIAO)
        REFERENCES REGIOES(ID_REGIAO),
    CONSTRAINT CK_GRAVIDADE CHECK (
        GRAVIDADE IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')
    )
);

CREATE TABLE ANALISE_RISCO (
    ID_ANALISE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_REGIAO NUMBER NOT NULL,
    DATA_ANALISE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PONTUACAO_RISCO NUMBER(5,2),
    NIVEL_RISCO VARCHAR2(20),
    JUSTIFICATIVA VARCHAR2(500),
    CONSTRAINT PK_ANALISE_RISCO PRIMARY KEY (ID_ANALISE),
    CONSTRAINT FK_RISCO_REGIAO FOREIGN KEY (ID_REGIAO)
        REFERENCES REGIOES(ID_REGIAO),
    CONSTRAINT CK_NIVEL_RISCO CHECK (
        NIVEL_RISCO IN ('BAIXO', 'MODERADO', 'ALTO', 'CRITICO')
    )
);

