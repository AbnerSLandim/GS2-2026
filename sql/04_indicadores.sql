-- 1. CHUVA PREVISTA NAS PROXIMAS 24 HORAS POR REGIAO
SELECT
    R.NOME_REGIAO,
    COUNT(*) AS HORAS_ANALISADAS,
    ROUND(SUM(C.PRECIPITACAO_MM), 2) AS CHUVA_PREVISTA_24H
FROM DADOS_CLIMATICOS C
JOIN REGIOES R ON R.ID_REGIAO = C.ID_REGIAO
WHERE C.TIPO_DADO = 'PREVISAO'
  AND C.DATA_PREVISAO >= CURRENT_TIMESTAMP
  AND C.DATA_PREVISAO < CURRENT_TIMESTAMP + INTERVAL '24' HOUR
GROUP BY R.NOME_REGIAO
ORDER BY CHUVA_PREVISTA_24H DESC;

-- 2. TEMPERATURA E UMIDADE MEDIAS NAS PROXIMAS 24 HORAS
SELECT
    R.NOME_REGIAO,
    ROUND(AVG(C.TEMPERATURA), 1) AS TEMPERATURA_MEDIA,
    ROUND(AVG(C.UMIDADE), 1) AS UMIDADE_MEDIA
FROM DADOS_CLIMATICOS C
JOIN REGIOES R ON R.ID_REGIAO = C.ID_REGIAO
WHERE C.TIPO_DADO = 'PREVISAO'
  AND C.DATA_PREVISAO >= CURRENT_TIMESTAMP
  AND C.DATA_PREVISAO < CURRENT_TIMESTAMP + INTERVAL '24' HOUR
GROUP BY R.NOME_REGIAO
ORDER BY R.NOME_REGIAO;

-- 3. VENTO MEDIO E VELOCIDADE MAXIMA NAS PROXIMAS 24 HORAS
SELECT
    R.NOME_REGIAO,
    ROUND(AVG(C.VELOCIDADE_VENTO), 1) AS VENTO_MEDIO,
    ROUND(MAX(C.VELOCIDADE_VENTO), 1) AS VENTO_MAXIMO
FROM DADOS_CLIMATICOS C
JOIN REGIOES R ON R.ID_REGIAO = C.ID_REGIAO
WHERE C.TIPO_DADO = 'PREVISAO'
  AND C.DATA_PREVISAO >= CURRENT_TIMESTAMP
  AND C.DATA_PREVISAO < CURRENT_TIMESTAMP + INTERVAL '24' HOUR
GROUP BY R.NOME_REGIAO
ORDER BY VENTO_MAXIMO DESC;

-- 4. TOTAL DE OCORRENCIAS HISTORICAS POR REGIAO
SELECT
    R.NOME_REGIAO,
    COUNT(O.ID_OCORRENCIA) AS TOTAL_OCORRENCIAS
FROM REGIOES R
LEFT JOIN OCORRENCIAS O ON O.ID_REGIAO = R.ID_REGIAO
GROUP BY R.NOME_REGIAO
ORDER BY TOTAL_OCORRENCIAS DESC;

-- 5. OCORRENCIAS ALTAS E CRITICAS POR REGIAO
SELECT
    R.NOME_REGIAO,
    COUNT(O.ID_OCORRENCIA) AS TOTAL_OCORRENCIAS,
    SUM(CASE WHEN O.GRAVIDADE = 'ALTA' THEN 1 ELSE 0 END) AS OCORRENCIAS_ALTAS,
    SUM(CASE WHEN O.GRAVIDADE = 'CRITICA' THEN 1 ELSE 0 END) AS OCORRENCIAS_CRITICAS
FROM REGIOES R
LEFT JOIN OCORRENCIAS O ON O.ID_REGIAO = R.ID_REGIAO
GROUP BY R.NOME_REGIAO
ORDER BY TOTAL_OCORRENCIAS DESC;

-- 6. ANALISE DE RISCO MAIS RECENTE DE CADA REGIAO
SELECT
    R.NOME_REGIAO,
    A.PONTUACAO_RISCO,
    A.NIVEL_RISCO,
    A.JUSTIFICATIVA,
    A.DATA_ANALISE
FROM REGIOES R
JOIN ANALISE_RISCO A ON A.ID_REGIAO = R.ID_REGIAO
WHERE A.DATA_ANALISE = (
    SELECT MAX(A2.DATA_ANALISE)
    FROM ANALISE_RISCO A2
    WHERE A2.ID_REGIAO = A.ID_REGIAO
)
ORDER BY A.PONTUACAO_RISCO DESC;

-- 7. QUANTIDADE DE REGIOES POR NIVEL DE RISCO (ANALISE MAIS RECENTE)
SELECT
    NIVEL_RISCO,
    COUNT(*) AS TOTAL_REGIOES
FROM (
    SELECT A.ID_REGIAO, A.NIVEL_RISCO,
           ROW_NUMBER() OVER (
               PARTITION BY A.ID_REGIAO
               ORDER BY A.DATA_ANALISE DESC, A.ID_ANALISE DESC
           ) AS RN
    FROM ANALISE_RISCO A
)
WHERE RN = 1
GROUP BY NIVEL_RISCO
ORDER BY TOTAL_REGIOES DESC;

-- 8. DADOS CLIMATICOS HORA A HORA (PARA GRAFICO DE LINHA)
-- Ajuste o intervalo conforme o periodo que deseja visualizar.
SELECT
    R.NOME_REGIAO,
    C.DATA_PREVISAO,
    C.PRECIPITACAO_MM,
    C.VELOCIDADE_VENTO,
    C.TEMPERATURA,
    C.UMIDADE
FROM DADOS_CLIMATICOS C
JOIN REGIOES R ON R.ID_REGIAO = C.ID_REGIAO
WHERE C.TIPO_DADO = 'PREVISAO'
ORDER BY C.DATA_PREVISAO, R.NOME_REGIAO;

-- 9. CONSULTA DE DIAGNOSTICO: INTERVALO E QUANTIDADE DE PREVISOES
SELECT
    CURRENT_TIMESTAMP AS HORARIO_BANCO,
    MIN(DATA_PREVISAO) AS PRIMEIRA_PREVISAO,
    MAX(DATA_PREVISAO) AS ULTIMA_PREVISAO,
    COUNT(*) AS TOTAL_REGISTROS
FROM DADOS_CLIMATICOS
WHERE TIPO_DADO = 'PREVISAO';

-- 10. COMPARACAO ENTRE CLIMA E HISTORICO SEM MULTIPLICAR LINHAS
-- Resume clima e ocorrencias separadamente antes de juntar os resultados.
SELECT
    R.NOME_REGIAO,
    C.CHUVA_PREVISTA_24H,
    C.VENTO_MAXIMO_24H,
    O.TOTAL_OCORRENCIAS,
    O.OCORRENCIAS_ALTAS,
    O.OCORRENCIAS_CRITICAS
FROM REGIOES R
LEFT JOIN (
    SELECT
        ID_REGIAO,
        ROUND(SUM(PRECIPITACAO_MM), 2) AS CHUVA_PREVISTA_24H,
        ROUND(MAX(VELOCIDADE_VENTO), 2) AS VENTO_MAXIMO_24H
    FROM DADOS_CLIMATICOS
    WHERE TIPO_DADO = 'PREVISAO'
      AND DATA_PREVISAO >= CURRENT_TIMESTAMP
      AND DATA_PREVISAO < CURRENT_TIMESTAMP + INTERVAL '24' HOUR
    GROUP BY ID_REGIAO
) C ON C.ID_REGIAO = R.ID_REGIAO
LEFT JOIN (
    SELECT
        ID_REGIAO,
        COUNT(*) AS TOTAL_OCORRENCIAS,
        SUM(CASE WHEN GRAVIDADE = 'ALTA' THEN 1 ELSE 0 END) AS OCORRENCIAS_ALTAS,
        SUM(CASE WHEN GRAVIDADE = 'CRITICA' THEN 1 ELSE 0 END) AS OCORRENCIAS_CRITICAS
    FROM OCORRENCIAS
    GROUP BY ID_REGIAO
) O ON O.ID_REGIAO = R.ID_REGIAO
ORDER BY C.CHUVA_PREVISTA_24H DESC NULLS LAST;

